import VMPaneCore

/// HID keyboard usages → PC/XT set-1 scancodes, as SPICE's inputs channel takes them (keys with an E0
/// prefix are `0x100 | code`). The display maps a real key press macOS key code → usage (`KeyNames`) →
/// scancode, so the Mac's Command keys arrive as the Windows keys.
public enum SpiceKeyMap {
    public static func scancode(forHIDUsage usage: UInt16) -> Int? { scancodes[usage] }

    /// The scancode for a macOS key event, or nil for keys without one (Fn).
    public static func scancode(forMacKeyCode code: UInt16) -> Int? {
        KeyNames.hidUsage(forMacKeyCode: code).flatMap(scancode(forHIDUsage:))
    }

    static let extended = 0x100

    static let scancodes: [UInt16: Int] = {
        // A–Z, then 1–9, 0.
        let letters = [
            0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18, 0x19, 0x10, 0x13, 0x1F,
            0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C,
        ]
        var map: [UInt16: Int] = [:]
        for (offset, code) in letters.enumerated() { map[UInt16(0x04 + offset)] = code }
        for offset in 0..<10 { map[UInt16(0x1E + offset)] = 0x02 + offset }
        for offset in 0..<10 { map[UInt16(0x3A + offset)] = 0x3B + offset }  // F1–F10
        let ext = extended
        let named: [UInt16: Int] = [
            0x28: 0x1C, 0x29: 0x01, 0x2A: 0x0E, 0x2B: 0x0F, 0x2C: 0x39, 0x2D: 0x0C, 0x2E: 0x0D, 0x2F: 0x1A, 0x30: 0x1B,
            0x31: 0x2B, 0x33: 0x27, 0x34: 0x28, 0x35: 0x29, 0x36: 0x33, 0x37: 0x34, 0x38: 0x35, 0x39: 0x3A,
            0x44: 0x57, 0x45: 0x58,  // F11, F12
            0x46: ext | 0x37, 0x47: 0x46, 0x49: ext | 0x52, 0x4A: ext | 0x47, 0x4B: ext | 0x49, 0x4C: ext | 0x53, 0x4D: ext | 0x4F,
            0x4E: ext | 0x51, 0x4F: ext | 0x4D, 0x50: ext | 0x4B, 0x51: ext | 0x50, 0x52: ext | 0x48,
            // Keypad
            0x53: 0x45, 0x54: ext | 0x35, 0x55: 0x37, 0x56: 0x4A, 0x57: 0x4E, 0x58: ext | 0x1C, 0x59: 0x4F, 0x5A: 0x50, 0x5B: 0x51,
            0x5C: 0x4B, 0x5D: 0x4C, 0x5E: 0x4D, 0x5F: 0x47, 0x60: 0x48, 0x61: 0x49, 0x62: 0x52, 0x63: 0x53, 0x67: 0x59,
            // Non-US backslash, Application (menu), F13–F20, media, JIS
            0x64: 0x56, 0x65: ext | 0x5D, 0x68: 0x64, 0x69: 0x65, 0x6A: 0x66, 0x6B: 0x67, 0x6C: 0x68, 0x6D: 0x69, 0x6E: 0x6A,
            0x6F: 0x6B, 0x7F: ext | 0x20, 0x80: ext | 0x30, 0x81: ext | 0x2E, 0x87: 0x73, 0x88: 0x70, 0x89: 0x7D, 0x8A: 0x79,
            0x8B: 0x7B, 0x90: 0x72, 0x91: 0x71,
            // Modifiers: Control, Shift, Alt (Option), GUI (Command → Windows key); left, then right.
            0xE0: 0x1D, 0xE1: 0x2A, 0xE2: 0x38, 0xE3: ext | 0x5B, 0xE4: ext | 0x1D, 0xE5: 0x36, 0xE6: ext | 0x38, 0xE7: ext | 0x5C,
        ]
        map.merge(named) { $1 }
        return map
    }()
}
