#!/usr/bin/env bash
# Vendors CocoaSpice (utmapp/CocoaSpice, Apache-2.0) into Packages/VMPaneSpice at a pinned commit: the
# no-USB sources and the Metal renderer, without its bundled third-party headers (VMPaneSpice builds against
# the headers of the libraries we ship, SpiceSDK/), then applies Packages/VMPaneSpice/patches/*.patch and
# embeds the shaders as source (CSShadersSource.h). The result is committed; rerun after changing the pin
# or a patch, and review the diff. Usage: scripts/vendor-cocoaspice.sh [--check]
set -euo pipefail
cd "$(dirname "$0")/.."

repo=https://github.com/utmapp/CocoaSpice.git
commit=d8d29fc810047a3ddcebb351cdadc8fe4b4f308d
package=Packages/VMPaneSpice
check=0
[[ ${1:-} == --check ]] && check=1

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
git clone --quiet "$repo" "$work/src"
git -C "$work/src" checkout --quiet "$commit"
out=$work/out
mkdir -p "$out/CocoaSpice" "$out/CocoaSpiceRenderer"
# The no-USB target's sources (its USB headers stay: CocoaSpice.h includes them), no ExternalHeaders, no
# GStreamer static-plugin init.
rsync -a --exclude ExternalHeaders --exclude 'CSUSB*.m' --exclude 'CSUSB*+Protected.h' --exclude 'gst_ios_init.*' \
    "$work/src/Sources/CocoaSpice/" "$out/CocoaSpice/"
rsync -a "$work/src/Sources/CocoaSpiceRenderer/" "$out/CocoaSpiceRenderer/"
cp "$work/src/LICENSE" "$out/CocoaSpice/LICENSE"
for patch in "$package"/patches/*.patch; do
    git -C "$out" apply --whitespace=nowarn "$PWD/$patch"
done

# The shader source, with its one local header inlined, as a C string literal.
{
    echo "// Generated by scripts/vendor-cocoaspice.sh from CSShaders.metal and CSShaderTypes.h: do not edit."
    echo "static const char CSShadersSource[] ="
    { grep -v '^#import "include/CSShaderTypes.h"' "$out/CocoaSpiceRenderer/CSShaders.metal" | sed '/^#include <simd\/simd.h>/r '"$out/CocoaSpiceRenderer/include/CSShaderTypes.h"; } \
        | sed 's/\\/\\\\/g; s/"/\\"/g; s/^/    "/; s/$/\\n"/'
    echo "    ;"
} >"$out/CocoaSpiceRenderer/CSShadersSource.h"

if ((check)); then
    diff -r "$out/CocoaSpice" "$package/Sources/CocoaSpice" && diff -r "$out/CocoaSpiceRenderer" "$package/Sources/CocoaSpiceRenderer" \
        || { echo "vendor-cocoaspice: Packages/VMPaneSpice differs from the pinned CocoaSpice + patches" >&2; exit 1; }
    echo "vendor-cocoaspice: up to date"
    exit 0
fi
rm -rf "$package/Sources/CocoaSpice" "$package/Sources/CocoaSpiceRenderer"
mkdir -p "$package/Sources"
cp -R "$out/CocoaSpice" "$out/CocoaSpiceRenderer" "$package/Sources/"
echo "vendor-cocoaspice: CocoaSpice $commit vendored into $package/Sources"
