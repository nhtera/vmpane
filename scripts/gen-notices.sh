#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES.md from the Swift package pins (project.yml, exact versions),
# agent/Cargo.lock (cargo about) and qemu/deps.lock (when the QEMU build exists).
# Output is deterministic so CI can diff it. Usage: scripts/gen-notices.sh [--check]
set -euo pipefail
cd "$(dirname "$0")/.."
source scripts/lib/env.sh

out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# Swift packages are pinned with exactVersion in project.yml; licences come from the resolved checkouts.
spm=build/spm
xcodegen generate --quiet
xcodebuild -resolvePackageDependencies -project VMPane.xcodeproj -scheme VMPane \
    -clonedSourcePackagesDirPath "$spm" >/dev/null

resolved=VMPane.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved
{
    echo "# Third-party notices"
    echo
    echo "Generated by \`scripts/gen-notices.sh\`. Do not edit by hand."
    echo
    echo "## Swift packages (macOS app)"
    echo
    if [[ -f "$resolved" ]]; then
        jq -r '.pins | sort_by(.identity)[] | [.identity, .location, (.state.version // .state.revision)] | @tsv' "$resolved" |
            while IFS=$'\t' read -r name url version; do
                echo "### $name $version"
                echo
                echo "<$url>"
                echo
                checkout="$spm/checkouts/$name"
                [[ -d "$checkout" ]] || { echo "error: no checkout for $name in $spm" >&2; exit 1; }
                license=$(find "$checkout" -maxdepth 1 -iname 'LICENSE*' | LC_ALL=C sort | head -1)
                [[ -n "$license" ]] || { echo "error: $name has no LICENSE file" >&2; exit 1; }
                echo '```'
                cat "$license"
                echo '```'
                echo
            done
    fi
    echo "## Rust crates (guest agent)"
    echo
    rust=$(cd agent && cargo about generate --locked --fail about.hbs)
    echo "${rust:-None.}"
    if [[ -f qemu/deps.lock ]]; then
        echo "## QEMU and its libraries (Windows guests)"
        echo
        echo "Built from source by \`qemu/scripts/build-deps.sh\` (see \`qemu/BUILDING.md\`); the corresponding source"
        echo "is published with each release."
        echo
        echo "| Component | Version | Licence | Source |"
        echo "|---|---|---|---|"
        jq -r '.components[] | select(.role == "runtime") | "| \(.name) | \(.version) | \(.license) | <\(.url)> |"' qemu/deps.lock
        echo
    fi
} >"$tmp"

if [[ "${1:-}" == --check ]]; then
    if ! diff -u "$out" "$tmp"; then
        echo "error: $out is out of date; run scripts/gen-notices.sh" >&2
        exit 1
    fi
    echo "notices: up to date"
else
    mv "$tmp" "$out"
    chmod 644 "$out"
    trap - EXIT
    echo "notices: wrote $out"
fi
