#!/usr/bin/env bash
# docs/cli.md from vmpane's own --help (every command and subcommand). Usage: scripts/gen-cli-docs.sh [app]
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
app=${1:-$root/build/Debug/VMPane.app}
cli="$app/Contents/Helpers/vmpane"
[[ -x $cli ]] || { echo "no vmpane at $cli (scripts/build.sh first)" >&2; exit 1; }
out="$root/docs/cli.md"
{
    echo "# vmpane"
    echo
    echo "VMPane's command-line tool (\`VMPane.app/Contents/Helpers/vmpane\`; \`vmpane install-cli\` puts it on the PATH)."
    echo "Generated by \`scripts/gen-cli-docs.sh\` from \`vmpane --help\`."
    echo
    echo "Exit codes: 0 ok, 1 failed, 64 bad arguments, 66 no such VM, 69 helper or guest agent unavailable,"
    echo "75 try again (busy, wrong state), 77 refused by the VM's agent policy or the kill switch; \`vmpane exec\`"
    echo "exits with the command's own code."
    echo
    commands=("")
    for command in $("$cli" --help | awk '/^SUBCOMMANDS:/ {on=1; next} on && /^  [a-z]/ {print $1}'); do
        commands+=("$command")
        for sub in $("$cli" "$command" --help | awk '/^SUBCOMMANDS:/ {on=1; next} on && /^  [a-z]/ {print $1}'); do
            commands+=("$command $sub")
        done
    done
    for command in "${commands[@]}"; do
        echo "## vmpane${command:+ $command}"
        echo
        echo '```'
        # shellcheck disable=SC2086
        "$cli" $command --help | sed -e 's/[[:space:]]*$//'
        echo '```'
        echo
    done
} >"$out"
echo "wrote $out"
